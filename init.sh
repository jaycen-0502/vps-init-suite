prompt_read() {
    local prompt_text="$1"
    local var_name="$2"
    local raw=""
    if ( : < /dev/tty ) 2>/dev/null; then
        if ! read -r -p "$prompt_text" raw </dev/tty; then
            echo ""
            raw=""
        fi
    else
        if ! read -r -p "$prompt_text" raw; then
            echo ""
            raw=""
        fi
    fi
    raw=$(printf '%s' "$raw" | tr -d '\r' | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')
    printf -v "$var_name" '%s' "$raw"
}

