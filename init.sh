# 清理可能覆盖本脚本参数的旧版/第三方 sysctl 配置
clean_conflicting_sysctl() {
    local conflict_files=(
        98-disable-ipv6.conf
        99-proxy-speed.conf
        99-conntrack.conf
        99-swap.conf
        99-vps-init-suite.conf
        99-vps-init-suite-swap.conf
        99-vps-init-opt.conf
        99-us-speed-test.conf
        99-1g-high-conn.conf
        99-high-conn.conf
        99-lowmem-patch.conf
        99-us-200m.conf
        99-zzz-lowmem-override.conf
        99-proxy-experience.conf
        99-fix-ipv6.conf
    )
    local f path backup_dir=""
    for f in "${conflict_files[@]}"; do
        path="/etc/sysctl.d/${f}"
        if [[ -e "$path" && "$path" != "$SYSCTL_TARGET" ]]; then
            if [[ -z "$backup_dir" ]]; then
                backup_dir="${BACKUP_ROOT}/init-conflicts-$(date +%Y%m%d-%H%M%S)"
                mkdir -p "$backup_dir"
            fi
            cp -a "$path" "${backup_dir}/${f}" 2>/dev/null || true
            rm -f -- "$path"
        fi
    done
    if [[ -n "$backup_dir" ]]; then
        log_warn "已备份并清理旧版冲突 sysctl 碎片（防止参数覆盖打架），备份目录: ${backup_dir}"
    fi
}

# ==============================================================================
# 智能 DNS 配置模块（兼容 systemd-resolved 0ms 本地缓存 & 防 DHCP 覆盖锁定）
# ==============================================================================
configure_smart_dns() {
    local def_dev=""
    def_dev=$(ip -4 route show default 2>/dev/null | awk '{print $5; exit}')
    local dhcp_intercepted=0

    if systemctl is-active --quiet systemd-resolved 2>/dev/null; then
        mkdir -p "$RESOLVED_DROPIN_DIR"
        cat << EOF > "$RESOLVED_DROPIN_FILE"
# Managed by vps-init-suite init.sh v${SCRIPT_VERSION}
[Resolve]
DNS=8.8.8.8 1.1.1.1
FallbackDNS=8.8.4.4 1.0.0.1
DNSSEC=no
Cache=yes
EOF

        # 从网络管理层拦截接口级 DHCP DNS 覆盖（严禁直接修改原始 Netplan YAML）
        if [[ -n "$def_dev" ]]; then
            if systemctl is-active --quiet systemd-networkd 2>/dev/null; then
                local net_file="" net_base=""
                net_file=$(SYSTEMD_COLORS=0 networkctl status "$def_dev" --no-pager 2>/dev/null | awk -F': ' '/Network File/ {print $2; exit}' | tr -d '[:space:]')
                if [[ -n "$net_file" && "$net_file" != "n/a" && "$net_file" != "none" ]]; then
                    net_base=$(basename "$net_file")
                    if [[ -n "$net_base" ]]; then
                        mkdir -p "/etc/systemd/network/${net_base}.d"
                        cat << EOF > "/etc/systemd/network/${net_base}.d/99-vps-init-dns.conf"
# Managed by vps-init-suite init.sh v${SCRIPT_VERSION}
[Network]
DNS=
DNS=8.8.8.8
DNS=1.1.1.1

[DHCPv4]
UseDNS=false

[DHCPv6]
UseDNS=false

[IPv6AcceptRA]
UseDNS=false
EOF
                        networkctl reload 2>/dev/null || true
                        dhcp_intercepted=1
                    fi
                fi
            fi

            if systemctl is-active --quiet NetworkManager 2>/dev/null || command -v nmcli >/dev/null 2>&1; then
                local nm_uuid=""
                nm_uuid=$(nmcli -t -f DEVICE,UUID connection show --active 2>/dev/null | awk -F: -v dev="$def_dev" '$1 == dev {print $2; exit}')
                if [[ -n "$nm_uuid" ]]; then
                    nmcli connection modify "$nm_uuid" ipv4.ignore-auto-dns yes ipv4.dns "8.8.8.8 1.1.1.1" ipv6.ignore-auto-dns yes 2>/dev/null || true
                    nmcli device reapply "$def_dev" 2>/dev/null || true
                    dhcp_intercepted=1
                fi
            fi
        fi

        systemctl restart systemd-resolved 2>/dev/null || true
        sleep 1
        if [[ -n "$def_dev" ]] && command -v resolvectl >/dev/null 2>&1; then
            resolvectl dns "$def_dev" 8.8.8.8 1.1.1.1 2>/dev/null || true
            resolvectl flush-caches 2>/dev/null || true
        fi

        if [[ "$dhcp_intercepted" -eq 1 ]]; then
            DNS_MODE="systemd-resolved-locked"
            log_ok "已通过 systemd-resolved 配置就近 ECS DNS (8.8.8.8 主用 / 1.1.1.1 备用)，开启 0ms 本地缓存并拦截接口级 DHCP 抢占。"
        else
            DNS_MODE="systemd-resolved"
            log_ok "已通过 systemd-resolved 配置就近 ECS DNS (8.8.8.8 主用 / 1.1.1.1 备用) 并开启本地缓存。"
        fi
    else
        if command -v chattr >/dev/null 2>&1; then
            chattr -i /etc/resolv.conf 2>/dev/null || true
        fi
        if [[ -L /etc/resolv.conf ]]; then
            local bdir="${BACKUP_ROOT}/dns-$(date +%Y%m%d-%H%M%S)"
            mkdir -p "$bdir"
            cp -a /etc/resolv.conf "${bdir}/resolv.conf" 2>/dev/null || true
            rm -f -- /etc/resolv.conf
        fi
        cat << EOF > /etc/resolv.conf
# Managed by vps-init-suite init.sh v${SCRIPT_VERSION}
options timeout:1 attempts:2 single-request-reopen
nameserver 8.8.8.8
nameserver 1.1.1.1
EOF
        if command -v chattr >/dev/null 2>&1 && chattr +i /etc/resolv.conf 2>/dev/null; then
            DNS_MODE="resolv.conf-locked"
            log_ok "已写入纯净 ECS DNS (8.8.8.8 主用 / 1.1.1.1 备用) 并加锁免疫 DHCP/重启覆写。"
        else
            DNS_MODE="resolv.conf"
            log_ok "已写入纯净 ECS DNS (8.8.8.8 主用 / 1.1.1.1 备用)。"
        fi
    fi
}

# ==============================================================================
# 运行时网络规则持久化（IPv4/v6 MSS + 自适应 initcwnd + 可选 fq maxrate 软封顶）
# ==============================================================================
configure_runtime_net_rules() {
    mkdir -p "$(dirname "$RUNTIME_SCRIPT")"
    cat << 'EOF' > "$RUNTIME_SCRIPT"
#!/usr/bin/env bash
# Managed by vps-init-suite init.sh
set -u

IPV6_ENABLED=0
INIT_CWND=20
FQ_MAXRATE_MBIT=0
if [[ -r /etc/default/vps-init-opt ]]; then
    # shellcheck disable=SC1091
    source /etc/default/vps-init-opt
fi

# 1. IPv4 TCP MSS 1380 幂等钳制（仅优化包长，不拦截任何端口）
IPT4=$(command -v iptables 2>/dev/null || echo "/sbin/iptables")
if [[ -x "$IPT4" ]]; then
    "$IPT4" -w 5 -t mangle -C POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1380 2>/dev/null || \
    "$IPT4" -w 5 -t mangle -A POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1380 2>/dev/null || true
fi

# 2. 双栈启用时补齐 IPv6 TCP MSS 1340 幂等钳制（IPv6 包头比 IPv4 多 20 字节）
IPT6=$(command -v ip6tables 2>/dev/null || echo "/sbin/ip6tables")
if [[ "${IPV6_ENABLED:-0}" == "1" && -x "$IPT6" ]]; then
    "$IPT6" -w 5 -t mangle -C POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1340 2>/dev/null || \
    "$IPT6" -w 5 -t mangle -A POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1340 2>/dev/null || true
elif [[ -x "$IPT6" ]]; then
    while "$IPT6" -w 5 -t mangle -C POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1340 2>/dev/null; do
        "$IPT6" -w 5 -t mangle -D POSTROUTING -p tcp --tcp-flags SYN,RST SYN -j TCPMSS --set-mss 1340 2>/dev/null || break
    done
fi

# 3. 设置默认 IPv4 路由自适应 initcwnd / initrwnd（近程 32 / 跨洋 20 / 高并发 16）
IP_BIN=$(command -v ip 2>/dev/null || echo "/sbin/ip")
DEF_DEV=""
if [[ -x "$IP_BIN" ]]; then
    DEF_DEV=$("$IP_BIN" -4 route show default 2>/dev/null | awk '{print $5; exit}')
    if [[ "${INIT_CWND:-20}" =~ ^[0-9]+$ ]] && (( INIT_CWND > 0 )); then
        DEF_ROUTE=$("$IP_BIN" -4 route show default 2>/dev/null | head -n1 | sed -E 's/[[:space:]]+initcwnd[[:space:]]+[0-9]+//g; s/[[:space:]]+initrwnd[[:space:]]+[0-9]+//g; s/[[:space:]]+$//')
        if [[ -n "$DEF_ROUTE" ]]; then
            # shellcheck disable=SC2086
            "$IP_BIN" -4 route change $DEF_ROUTE initcwnd "$INIT_CWND" initrwnd "$INIT_CWND" 2>/dev/null || true
        fi
    fi
fi

# 4. 可选 fq maxrate 单流防撞墙软封顶（自动兼容单队列与 mq 多队列，且支持 off 干净回退）
TC_BIN=$(command -v tc 2>/dev/null || echo "/sbin/tc")
if [[ -x "$TC_BIN" && -n "$DEF_DEV" ]]; then
    QDISC_OUT=$("$TC_BIN" qdisc show dev "$DEF_DEV" 2>/dev/null || true)
    if [[ "${FQ_MAXRATE_MBIT:-0}" =~ ^[0-9]+$ ]] && (( FQ_MAXRATE_MBIT > 0 )); then
        if grep -qE '^qdisc mq ' <<<"$QDISC_OUT"; then
            while read -r parent_id; do
                [[ -n "$parent_id" ]] && "$TC_BIN" qdisc replace dev "$DEF_DEV" parent "$parent_id" fq maxrate "${FQ_MAXRATE_MBIT}mbit" 2>/dev/null || true
            done < <(awk '{for(i=1;i<=NF;i++) if($i=="parent" && $(i+1) ~ /^[0-9a-fA-F]*:[0-9a-fA-F]+$/) print $(i+1)}' <<<"$QDISC_OUT")
        else
            "$TC_BIN" qdisc replace dev "$DEF_DEV" root fq maxrate "${FQ_MAXRATE_MBIT}mbit" 2>/dev/null || true
        fi
    elif grep -qi 'maxrate' <<<"$QDISC_OUT"; then
        # 切换为关闭限速时，清除此前挂载的 maxrate 封顶并保留 fq / mq 结构
        if grep -qE '^qdisc mq ' <<<"$QDISC_OUT"; then
            while read -r parent_id; do
                [[ -n "$parent_id" ]] && "$TC_BIN" qdisc replace dev "$DEF_DEV" parent "$parent_id" fq 2>/dev/null || true
            done < <(awk '{for(i=1;i<=NF;i++) if($i=="parent" && $(i+1) ~ /^[0-9a-fA-F]*:[0-9a-fA-F]+$/) print $(i+1)}' <<<"$QDISC_OUT")
        else
            "$TC_BIN" qdisc replace dev "$DEF_DEV" root fq 2>/dev/null || true
        fi
    fi
fi

# 5. 开机/网卡重载 DNS 纠偏（防止 DHCP 续租后回弹）
if systemctl is-active --quiet systemd-resolved 2>/dev/null && command -v resolvectl >/dev/null 2>&1; then
    if [[ -n "$DEF_DEV" ]]; then
        CUR_DNS=$(SYSTEMD_COLORS=0 resolvectl status "$DEF_DEV" 2>/dev/null | awk -F': ' '/Current DNS Server/ {print $2; exit}' | tr -d '[:space:]')
        if [[ "$CUR_DNS" != "8.8.8.8" ]]; then
            resolvectl dns "$DEF_DEV" 8.8.8.8 1.1.1.1 2>/dev/null || true
            resolvectl flush-caches 2>/dev/null || true
        fi
    fi
fi

exit 0
EOF
    chmod 0755 "$RUNTIME_SCRIPT"

    # 同步替换或写入 if-up.d 钩子，防止旧版 99-initcwnd (64) 或网卡重启覆盖
    if [[ -d /etc/network/if-up.d ]]; then
        cat << EOF > /etc/network/if-up.d/99-initcwnd
#!/bin/sh
# Managed by vps-init-suite init.sh v${SCRIPT_VERSION}
[ -x "${RUNTIME_SCRIPT}" ] && "${RUNTIME_SCRIPT}" >/dev/null 2>&1 || true
EOF
        chmod 0755 /etc/network/if-up.d/99-initcwnd
    fi

    cat << EOF > "$RUNTIME_SERVICE"
[Unit]
Description=Persist vps-init-suite TCP MSS Clamping, initcwnd and fq maxrate Tuning
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
ExecStart=${RUNTIME_SCRIPT}
RemainAfterExit=yes

[Install]
WantedBy=multi-user.target
EOF
    systemctl daemon-reload
    systemctl enable proxy-mss.service >/dev/null 2>&1 || true
    "$RUNTIME_SCRIPT"
}

# ==============================================================================
# 自适应网络计算模块（按“带宽 + 延迟 + 并发档位 + 物理内存 + 软封顶”动态计算）
# ==============================================================================
configure_adaptive_network() {
    local IN_BW="${1:-}"
    local IN_RTT="${2:-}"
    local IN_TIER="${3:-}"
    local IN_FQ="${4:-}"

    local MEM_TOTAL_MB CPU_CORES
    MEM_TOTAL_MB=$(awk '/^MemTotal:/ {print int($2/1024)}' /proc/meminfo 2>/dev/null || echo 1024)
    CPU_CORES=$(nproc 2>/dev/null || echo 1)

    # 1. 仅在缺少前 3 个核心参数且存在可用终端时进行无超时手动引导（完全兼容 3 参静默调用）
    if [[ -z "$IN_BW" || -z "$IN_RTT" || -z "$IN_TIER" ]]; then
        if ( : < /dev/tty ) 2>/dev/null || [[ -t 0 ]]; then
            echo ""
            echo "============================================================"
            echo " 本机硬件检测: ${CPU_CORES} 核 CPU | ${MEM_TOTAL_MB} MB 内存"
            echo " 延迟参考: 日本/亚太填 40 | 美西直连填 160 | 美国国际落地填 30"
            echo "============================================================"
            if [[ -z "$IN_BW" ]]; then
                while true; do
                    prompt_read " 1. 请输入机器带宽 Mbps [回车默认 500]: " IN_BW
                    [[ -z "$IN_BW" ]] && IN_BW=500
                    if [[ "$IN_BW" =~ ^[0-9]+$ ]] && (( 10#$IN_BW >= 1 && 10#$IN_BW <= 100000 )); then
                        IN_BW=$((10#$IN_BW))
                        break
                    fi
                    log_warn "请输入 1 到 100000 之间的纯数字（例如 200、250、500、1000）。"
                done
            fi
            if [[ -z "$IN_RTT" ]]; then
                while true; do
                    prompt_read " 2. 请输入典型延迟 ms   [回车默认 160]: " IN_RTT
                    [[ -z "$IN_RTT" ]] && IN_RTT=160
                    if [[ "$IN_RTT" =~ ^[0-9]+$ ]] && (( 10#$IN_RTT >= 1 && 10#$IN_RTT <= 2000 )); then
                        IN_RTT=$((10#$IN_RTT))
                        break
                    fi
                    log_warn "请输入 1 到 2000 之间的纯数字（日本填 40，美西填 160）。"
                done
            fi
            if [[ -z "$IN_TIER" ]]; then
                echo " 3. 请选择并发使用规模:"
                echo "    [1] 常规/低中并发 (500连接以内，单线程速度与4K/8K视频优先，1G机安全封顶12M)"
                echo "    [2] 多人高并发    (1000-3000+连接，防爆内存与极致稳定优先，严格封顶)"
                while true; do
                    prompt_read " 请选择 [1/2，回车默认 1]: " IN_TIER
                    [[ -z "$IN_TIER" ]] && IN_TIER=1
                    if [[ "$IN_TIER" == "1" || "$IN_TIER" == "2" ]]; then
                        break
                    fi
                    log_warn "无效选择，请输入 1 或 2。"
                done
            fi
            if [[ -z "$IN_FQ" ]]; then
                echo " 4. fq maxrate 单流防撞墙软封顶 (将 BBR 探速压在机房硬限速墙下方，压低重传):"
                echo "    [smart] 智能自动 (<=500M 且延迟>=100ms 按90%封顶，1G+/近程不限速) [推荐]"
                echo "    [auto]  强制按当前带宽 90% 封顶"
                echo "    [off]   关闭单流软封顶"
                echo "    或直接输入具体 Mbps 数字 (例如 225)"
                while true; do
                    prompt_read " 请输入 [smart/auto/off/数字，回车默认 smart]: " IN_FQ
                    [[ -z "$IN_FQ" ]] && IN_FQ="smart"
                    IN_FQ=$(printf '%s' "$IN_FQ" | tr '[:upper:]' '[:lower:]')
                    if [[ "$IN_FQ" == "smart" || "$IN_FQ" == "auto" || "$IN_FQ" == "off" || ( "$IN_FQ" =~ ^[0-9]+$ && 10#$IN_FQ -le 100000 ) ]]; then
                        break
                    fi
                    log_warn "无效输入，请输入 smart、auto、off 或正整数 Mbps。"
                done
            fi
            echo "============================================================"
        fi
    fi

    # 默认值与合法性兜底
    BW_MBPS="${IN_BW:-500}"
    RTT_MS="${IN_RTT:-160}"
    CONN_TIER="${IN_TIER:-1}"
    FQ_MAXRATE_ARG=$(printf '%s' "${IN_FQ:-smart}" | tr '[:upper:]' '[:lower:]')
    [[ "$BW_MBPS" =~ ^[0-9]+$ ]] && (( 10#$BW_MBPS > 0 )) && BW_MBPS=$((10#$BW_MBPS)) || BW_MBPS=500
    [[ "$RTT_MS" =~ ^[0-9]+$ ]] && (( 10#$RTT_MS > 0 )) && RTT_MS=$((10#$RTT_MS)) || RTT_MS=160
    [[ "$CONN_TIER" == "2" ]] || CONN_TIER=1

    # 2. 按 2.5 倍 BDP 计算目标窗口（抵消 Linux tcp_adv_win_scale=1 ~50% 元数据开销），对齐至精细阶梯
    local TARGET_BYTES=$(( BW_MBPS * RTT_MS * 125 * 5 / 2 ))
    if (( TARGET_BYTES <= 2097152 )); then
        TCP_MAX_BUF=2097152       # 2MB
    elif (( TARGET_BYTES <= 4194304 )); then
        TCP_MAX_BUF=4194304       # 4MB
    elif (( TARGET_BYTES <= 8388608 )); then
        TCP_MAX_BUF=8388608       # 8MB
    elif (( TARGET_BYTES <= 12582912 )); then
        TCP_MAX_BUF=12582912      # 12MB (200~250M @ 160ms 精准命中)
    elif (( TARGET_BYTES <= 16777216 )); then
        TCP_MAX_BUF=16777216      # 16MB
    elif (( TARGET_BYTES <= 25165824 )); then
        TCP_MAX_BUF=25165824      # 24MB (500M @ 160ms 精准命中)
    else
        TCP_MAX_BUF=33554432      # 32MB
    fi

    # 3. 结合物理内存与并发档位计算安全护栏与 tcp_notsent_lowat
    if (( MEM_TOTAL_MB <= 600 )); then
        TCP_DEF_BUF=16384
        BACKLOG_LIMIT=2048
        CONNTRACK_MAX=32768
        NOFILE_LIMIT=65535
        XUI_GOMEMLIMIT="180MiB"
        XUI_GOGC="50"
        XUI_OOM_SCORE="-300"
        JOURNAL_DISK_MAX="20M"
        JOURNAL_MEM_MAX="10M"
        (( TCP_MAX_BUF > 4194304 )) && TCP_MAX_BUF=4194304
        TCP_MEM_PAGES="8192 16384 32768"
        TCP_NOTSENT_LOWAT=16384
        PROFILE_DESC="512M-微型防爆档"
    elif (( MEM_TOTAL_MB <= 1500 )); then
        BACKLOG_LIMIT=4096
        CONNTRACK_MAX=65536
        NOFILE_LIMIT=65535
        XUI_GOGC="75"
        XUI_OOM_SCORE="-300"
        JOURNAL_DISK_MAX="30M"
        JOURNAL_MEM_MAX="15M"
        if (( CONN_TIER == 2 )); then
            # 1G 高并发防爆：严控单连接上限与内核总内存
            TCP_DEF_BUF=16384
            if (( RTT_MS >= 100 && TCP_MAX_BUF > 4194304 )); then
                TCP_MAX_BUF=4194304
            elif (( RTT_MS < 100 && TCP_MAX_BUF > 2097152 )); then
                TCP_MAX_BUF=2097152
            fi
            XUI_GOMEMLIMIT="350MiB"
            TCP_MEM_PAGES="16384 32768 65536"   # 硬顶 256MB
            TCP_NOTSENT_LOWAT=16384
            PROFILE_DESC="1G-高并发稳态档"
        else
            # 1G 低中并发极速：安全封顶 12MB（兼顾 1G 日本/美国高吞吐与防 OOM）
            TCP_DEF_BUF=32768
            (( TCP_MAX_BUF > 12582912 )) && TCP_MAX_BUF=12582912
            XUI_GOMEMLIMIT="320MiB"
            TCP_MEM_PAGES="20480 40960 71680"   # 硬顶 280MB
            TCP_NOTSENT_LOWAT=32768
            PROFILE_DESC="1G-均衡极速档"
        fi
    else
        BACKLOG_LIMIT=16384
        CONNTRACK_MAX=262144
        NOFILE_LIMIT=1048576
        XUI_GOGC="100"
        XUI_OOM_SCORE="-900"
        JOURNAL_DISK_MAX="100M"
        JOURNAL_MEM_MAX="30M"
        if (( MEM_TOTAL_MB <= 3000 )); then
            XUI_GOMEMLIMIT="1024MiB"
        else
            XUI_GOMEMLIMIT="2048MiB"
        fi
        local mem_high=$(( MEM_TOTAL_MB * 1024 / 4 / 4 ))
        TCP_MEM_PAGES="$((mem_high / 4)) $((mem_high / 2)) ${mem_high}"

        if (( CONN_TIER == 2 )); then
            TCP_DEF_BUF=32768
            (( TCP_MAX_BUF > 12582912 )) && TCP_MAX_BUF=12582912
            TCP_NOTSENT_LOWAT=32768
            PROFILE_DESC="大内存-高并发稳态档"
        else
            TCP_DEF_BUF=65536
            TCP_NOTSENT_LOWAT=65536
            PROFILE_DESC="大内存-跨洋极速档"
        fi
    fi

    # 4. 跨洋自适应 initcwnd / initrwnd
    if (( CONN_TIER == 2 )); then
        INIT_CWND=16
    elif (( RTT_MS >= 100 )); then
        INIT_CWND=20
    else
        INIT_CWND=32
    fi

    # 5. 智能解析 fq maxrate 防撞墙单流软封顶
    FQ_MAXRATE_MBIT=0
    if [[ "$FQ_MAXRATE_ARG" == "smart" ]]; then
        if (( BW_MBPS <= 500 && RTT_MS >= 100 )); then
            FQ_MAXRATE_MBIT=$(( BW_MBPS * 90 / 100 ))
        fi
    elif [[ "$FQ_MAXRATE_ARG" == "auto" ]]; then
        FQ_MAXRATE_MBIT=$(( BW_MBPS * 90 / 100 ))
    elif [[ "$FQ_MAXRATE_ARG" =~ ^[0-9]+$ ]] && (( 10#$FQ_MAXRATE_ARG > 0 )); then
        FQ_MAXRATE_MBIT=$((10#$FQ_MAXRATE_ARG))
    else
        FQ_MAXRATE_ARG="off"
    fi
    (( FQ_MAXRATE_MBIT > 0 && FQ_MAXRATE_MBIT < 10 )) && FQ_MAXRATE_MBIT=0

    local fq_desc="关闭"
    (( FQ_MAXRATE_MBIT > 0 )) && fq_desc="${FQ_MAXRATE_MBIT}Mbit (${FQ_MAXRATE_ARG})"

    log_ok "匹配方案: ${PROFILE_DESC} | 带宽: ${BW_MBPS}Mbps | 延迟: ${RTT_MS}ms (并发档位: ${CONN_TIER})"
    log_ok "缓冲参数: TCP初始=$((TCP_DEF_BUF/1024))KB, TCP上限=$((TCP_MAX_BUF/1048576))MB, notsent=$((TCP_NOTSENT_LOWAT/1024))KB, initcwnd=${INIT_CWND}, fq封顶=${fq_desc}, x-ui内存限制=${XUI_GOMEMLIMIT}"
}

# ==============================================================================
# 核心模块 1: VPS 稳定性与网络吞吐深度调优 (不启用任何防火墙)
# ==============================================================================
optimize_proxy_stability_and_speed() {
    log_info "开始执行 VPS 稳定性与网络吞吐深度调优（无防火墙模式 v${SCRIPT_VERSION}）..."

    # 0. 安装基础依赖
    if command -v apt-get >/dev/null 2>&1; then
        DEBIAN_FRONTEND=noninteractive apt-get update -qq
        DEBIAN_FRONTEND=noninteractive apt-get install -y -qq curl iptables iproute2 chrony cron kmod procps e2fsprogs >/dev/null 2>&1
    elif command -v dnf >/dev/null 2>&1; then
        dnf install -y -q curl iptables iproute chrony cronie kmod procps-ng e2fsprogs >/dev/null 2>&1
    fi

    # 1. 多维自适应网络计算 (带宽 + 延迟 + 并发档位 + 物理内存 + fq软封顶)
    configure_adaptive_network "$@"

    # 2. 自动探测残废 IPv6 (消除双栈域名 3.6s 超时与 Go Happy Eyeballs 300ms 回退)
    local disable_ipv6_block=""
    if ! curl -6 -s -I -m 3 https://www.gstatic.com/generate_204 >/dev/null 2>&1 && \
       ! curl -6 -s -I -m 3 https://cp.cloudflare.com/generate_204 >/dev/null 2>&1; then
        IPV6_ENABLED=0
        log_info "检测到当前 VPS 无有效 IPv6 公网出口，写入内核禁用规则（防假死黑洞）..."
        disable_ipv6_block="net.ipv6.conf.all.disable_ipv6 = 1
net.ipv6.conf.default.disable_ipv6 = 1
net.ipv6.conf.lo.disable_ipv6 = 1"
    else
        IPV6_ENABLED=1
        log_info "IPv6 公网出口连通性正常，保留双栈支持并同步开启 IPv6 MSS 1340 钳制。"
        disable_ipv6_block="net.ipv6.conf.all.disable_ipv6 = 0
net.ipv6.conf.default.disable_ipv6 = 0
net.ipv6.conf.lo.disable_ipv6 = 0"
    fi

    # 3. 清理旧冲突 sysctl 并校验内核 BBR 支持
    clean_conflicting_sysctl
    modprobe tcp_bbr 2>/dev/null || true

    local cc_algo="bbr"
    if ! sysctl -n net.ipv4.tcp_available_congestion_control 2>/dev/null | grep -qw bbr; then
        cc_algo=$(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null || echo "cubic")
        log_warn "当前内核未暴露 tcp_bbr 模块，暂保留 ${cc_algo}；建议升级至 4.9+ 内核以启用 BBR。"
    fi

    if [[ -f /etc/modules-load.d/nf_conntrack.conf ]]; then
        rm -f /etc/modules-load.d/nf_conntrack.conf
    fi
    mkdir -p /etc/modules-load.d
    echo "tcp_bbr" > /etc/modules-load.d/vps-init-opt.conf

    local conntrack_block=""
    if [[ -e /proc/sys/net/netfilter/nf_conntrack_max ]]; then
        conntrack_block="net.netfilter.nf_conntrack_max = ${CONNTRACK_MAX}
net.netfilter.nf_conntrack_tcp_timeout_established = 3600"
    fi

    cat << EOF > "$SYSCTL_TARGET"
# Managed by vps-init-suite init.sh v${SCRIPT_VERSION}
# Profile: ${PROFILE_DESC} (${BW_MBPS}Mbps / ${RTT_MS}ms / tier=${CONN_TIER} / initcwnd=${INIT_CWND} / fq_maxrate=${FQ_MAXRATE_MBIT}mbit)
vm.swappiness = 10
fs.file-max = ${NOFILE_LIMIT}
net.core.default_qdisc = fq
net.ipv4.tcp_congestion_control = ${cc_algo}
net.ipv4.tcp_slow_start_after_idle = 0
net.ipv4.tcp_no_metrics_save = 1
net.ipv4.tcp_frto = 2
net.ipv4.tcp_reordering = 6
net.ipv4.tcp_mtu_probing = 1
net.ipv4.tcp_base_mss = 1024
net.ipv4.tcp_fastopen = 2
net.ipv4.tcp_moderate_rcvbuf = 1
net.ipv4.tcp_window_scaling = 1
net.ipv4.tcp_sack = 1
net.ipv4.tcp_dsack = 1

# 自适应 TCP 缓冲 + 256KB UDP/QUIC 默认缓冲 (多图/HTTP3/4K视频加速)
net.core.rmem_max = ${TCP_MAX_BUF}
net.core.wmem_max = ${TCP_MAX_BUF}
net.core.rmem_default = 262144
net.core.wmem_default = 262144
net.ipv4.tcp_rmem = 4096 ${TCP_DEF_BUF} ${TCP_MAX_BUF}
net.ipv4.tcp_wmem = 4096 ${TCP_DEF_BUF} ${TCP_MAX_BUF}
net.ipv4.tcp_mem = ${TCP_MEM_PAGES}
net.ipv4.udp_rmem_min = 16384
net.ipv4.udp_wmem_min = 16384
net.ipv4.tcp_notsent_lowat = ${TCP_NOTSENT_LOWAT}

# 高并发连接复用与弱网握手容错 (SYN重试放宽至3降低多图网页裂图)
net.ipv4.tcp_tw_reuse = 1
net.ipv4.tcp_fin_timeout = 15
net.ipv4.tcp_syn_retries = 3
net.ipv4.tcp_synack_retries = 3
net.ipv4.tcp_orphan_retries = 1
net.ipv4.tcp_keepalive_time = 300
net.ipv4.tcp_keepalive_intvl = 15
net.ipv4.tcp_keepalive_probes = 3
net.ipv4.ip_local_port_range = 10240 65535
net.core.netdev_max_backlog = ${BACKLOG_LIMIT}
net.core.somaxconn = ${BACKLOG_LIMIT}
net.ipv4.tcp_max_syn_backlog = ${BACKLOG_LIMIT}

# IPv6 防假死策略
${disable_ipv6_block}
${conntrack_block}
EOF

    # 4. 文件描述符 (FD) 上限（修正通配符为 *）
    mkdir -p /etc/security/limits.d /etc/systemd/system.conf.d
    cat << EOF > /etc/security/limits.d/99-nofile.conf
* soft nofile ${NOFILE_LIMIT}
* hard nofile ${NOFILE_LIMIT}
root soft nofile ${NOFILE_LIMIT}
root hard nofile ${NOFILE_LIMIT}
EOF

    cat << EOF > /etc/systemd/system.conf.d/99-limits.conf
[Manager]
DefaultLimitNOFILE=${NOFILE_LIMIT}
EOF

    # 5. 自适应 Swap（跳过容器环境，按磁盘余量创建 2G/1G 防爆盘）
    local virt_type="none"
    command -v systemd-detect-virt >/dev/null 2>&1 && virt_type=$(systemd-detect-virt 2>/dev/null || echo "none")
    if [[ "$virt_type" == "openvz" || "$virt_type" == "lxc" ]]; then
        log_info "容器环境 (${virt_type}) 跳过 Swap 创建。"
    elif [[ -z "$(swapon --show=NAME --noheadings 2>/dev/null)" ]]; then
        local disk_avail_mb swap_mb=0
        disk_avail_mb=$(df -BM / | awk 'NR==2 {gsub("M",""); print $4}')
        if [[ "$disk_avail_mb" =~ ^[0-9]+$ ]]; then
            if (( disk_avail_mb >= 3500 )); then
                swap_mb=2048
            elif (( disk_avail_mb >= 2000 )); then
                swap_mb=1024
            fi
        fi
        if (( swap_mb > 0 )); then
            if [[ ! -f /swapfile ]]; then
                log_info "创建 $((swap_mb/1024))GB Swap 交换文件以防爆内存..."
                fallocate -l "${swap_mb}M" /swapfile 2>/dev/null || dd if=/dev/zero of=/swapfile bs=1M count="$swap_mb" status=none
                chmod 600 /swapfile
                mkswap /swapfile >/dev/null
            fi
            swapon /swapfile 2>/dev/null || true
            grep -qE '^/swapfile[[:space:]]+' /etc/fstab || echo '/swapfile none swap sw,nofail 0 0' >> /etc/fstab
        else
            log_warn "根分区剩余空间不足 2GB (${disk_avail_mb:-0}MB)，跳过 Swap 创建防止爆盘。"
        fi
    fi

    # 日志占用限制防小盘写满
    mkdir -p /etc/systemd/journald.conf.d
    rm -f /etc/systemd/journald.conf.d/90-vps-init-suite.conf
    cat << EOF > /etc/systemd/journald.conf.d/99-limit.conf
[Journal]
SystemMaxUse=${JOURNAL_DISK_MAX}
RuntimeMaxUse=${JOURNAL_MEM_MAX}
EOF
    systemctl restart systemd-journald 2>/dev/null || true

    # 6. 注入 x-ui 自适应防爆守护（含 GOMEMLIMIT / GOGC / OOMScoreAdjust）
    mkdir -p "$XUI_DROPIN_DIR"
    rm -f "${XUI_DROPIN_DIR}/override.conf" "${XUI_DROPIN_DIR}/90-vps-init-suite.conf"
    cat << EOF > "$XUI_DROPIN_FILE"
# Managed by vps-init-suite init.sh v${SCRIPT_VERSION}
[Service]
OOMScoreAdjust=${XUI_OOM_SCORE}
LimitNOFILE=${NOFILE_LIMIT}
LimitNPROC=${NOFILE_LIMIT}
Environment="GOMEMLIMIT=${XUI_GOMEMLIMIT}"
Environment="GOGC=${XUI_GOGC}"
Environment="GODEBUG=madvdontneed=1"
Restart=always
RestartSec=2s
EOF

    # 7. 智能防覆写 DNS 配置
    configure_smart_dns

    # 8. 持久化最终完整状态（含 INIT_CWND、FQ_MAXRATE_MBIT、IPV6_ENABLED 与 DNS_MODE）
    save_state

    # 9. 统一加载 sysctl 并显式再灌入本文件确保无覆盖
    sysctl --system >/dev/null 2>&1 || true
    sysctl -p "$SYSCTL_TARGET" >/dev/null 2>&1 || true

    # 10. 应用并持久化 TCP MSS 1380/1340、自适应 initcwnd 与可选 fq maxrate
    configure_runtime_net_rules

    # 11. Chrony 毫秒级网络授时 (保障 REALITY 与 TLS 严格握手时间窗口)
    log_info "配置 Chrony 毫秒级时间同步..."
    systemctl enable chrony >/dev/null 2>&1 || systemctl enable chronyd >/dev/null 2>&1 || true
    systemctl restart chrony 2>/dev/null || systemctl restart chronyd 2>/dev/null || true
    chronyc makestep >/dev/null 2>&1 || true

    # 仅在 x-ui 运行时重启使其立即加载 Go 内存限制与 OOM 保护
    if systemctl is-active --quiet x-ui 2>/dev/null; then
        systemctl restart x-ui 2>/dev/null || true
    fi

    log_ok "VPS 稳定性与网络吞吐调优完成（未开启任何防火墙拦截，端口全通）。"
}

# ==============================================================================
# 核心模块 2: 调优状态严格自检报告（实测值 vs 预期值逐项核对）
# ==============================================================================
verify_optimization() {
    load_state
    echo ""
    echo -e "${BOLD}${CYAN}==================== VPS 调优状态自检报告 (v${SCRIPT_VERSION}) ====================${NC}"

    local cc idle no_metrics frto rmem def_buf tcp_mem_raw tcp_mem_norm udp_def cur_cwnd cur_lowat cur_syn
    cc=$(sysctl -n net.ipv4.tcp_congestion_control 2>/dev/null || echo "unknown")
    idle=$(sysctl -n net.ipv4.tcp_slow_start_after_idle 2>/dev/null || echo "unknown")
    no_metrics=$(sysctl -n net.ipv4.tcp_no_metrics_save 2>/dev/null || echo "unknown")
    frto=$(sysctl -n net.ipv4.tcp_frto 2>/dev/null || echo "unknown")
    rmem=$(sysctl -n net.core.rmem_max 2>/dev/null || echo "0")
    def_buf=$(sysctl -n net.ipv4.tcp_rmem 2>/dev/null | awk '{print $2}' || echo "0")
    tcp_mem_raw=$(sysctl -n net.ipv4.tcp_mem 2>/dev/null || echo "unknown")
    tcp_mem_norm=$(printf '%s' "$tcp_mem_raw" | tr -s '[:space:]' ' ' | sed 's/^ //;s/ $//')
    udp_def=$(sysctl -n net.core.rmem_default 2>/dev/null || echo "0")
    cur_lowat=$(sysctl -n net.ipv4.tcp_notsent_lowat 2>/dev/null || echo "0")
    cur_syn=$(sysctl -n net.ipv4.tcp_syn_retries 2>/dev/null || echo "0")
    cur_cwnd=$(ip -4 route show default 2>/dev/null | grep -oE 'initcwnd[[:space:]]+[0-9]+' | awk '{print $2}' | head -n1 || true)

    local def_dev="" qdisc_out="" fq_active=0 fq_rate_str="无单流限速"
    def_dev=$(ip -4 route show default 2>/dev/null | awk '{print $5; exit}')
    if [[ -n "$def_dev" ]] && command -v tc >/dev/null 2>&1; then
        qdisc_out=$(tc qdisc show dev "$def_dev" 2>/dev/null || true)
        if grep -qw "fq" <<<"$qdisc_out"; then
            fq_active=1
            local cur_maxrate
            cur_maxrate=$(grep -oiE 'maxrate[[:space:]]+[^[:space:]]+' <<<"$qdisc_out" | head -n1 | awk '{print $2}')
            [[ -n "$cur_maxrate" ]] && fq_rate_str="软封顶=${cur_maxrate}"
        fi
    fi

    local rmem_mb="?" def_kb="?" udp_kb="?" lowat_kb="?"
    [[ "$rmem" =~ ^[0-9]+$ ]] && rmem_mb=$((rmem / 1048576))
    [[ "$def_buf" =~ ^[0-9]+$ ]] && def_kb=$((def_buf / 1024))
    [[ "$udp_def" =~ ^[0-9]+$ ]] && udp_kb=$((udp_def / 1024))
    [[ "$cur_lowat" =~ ^[0-9]+$ ]] && lowat_kb=$((cur_lowat / 1024))

    echo -e "1. 调优策略与并发模式     : ${GREEN}[INFO] ${PROFILE_DESC}${NC}"
    echo -e "   • 带宽与 RTT 设置        : ${BW_MBPS} Mbps / ${RTT_MS} ms (并发档位: ${CONN_TIER} | fq策略: ${FQ_MAXRATE_ARG:-off})"

    if [[ "$cc" == "bbr" && "$idle" == "0" && "$no_metrics" == "1" && "$fq_active" -eq 1 ]]; then
        if (( ${FQ_MAXRATE_MBIT:-0} > 0 )) && ! grep -qi "maxrate" <<<"$qdisc_out"; then
            echo -e "2. BBR + 主网卡 fq 队列   : ${YELLOW}[WARN] cc=${cc}, fq已生效但 maxrate(${FQ_MAXRATE_MBIT}Mbit) 未挂载，请检查 tc${NC}"
        else
            echo -e "2. BBR + 主网卡 fq 队列   : ${GREEN}[PASS] cc=${cc}, dev=${def_dev}(fq/${fq_rate_str}), idle=${idle}, frto=${frto}${NC}"
        fi
    elif [[ "$cc" == "bbr" && "$idle" == "0" && "$no_metrics" == "1" && "$fq_active" -eq 0 ]]; then
        echo -e "2. BBR + 主网卡 fq 队列   : ${YELLOW}[WARN] BBR已开，但主网卡(${def_dev:-未知})尚未切为 fq 队列，请执行一次 reboot 使 pacing 彻底生效！${NC}"
    else
        echo -e "2. BBR + 主网卡 fq 队列   : ${RED}[FAIL] cc=${cc}, idle=${idle}, no_metrics=${no_metrics}, fq=${fq_active}${NC}"
    fi

    if [[ "$rmem" == "$TCP_MAX_BUF" && "$def_buf" == "$TCP_DEF_BUF" && "$tcp_mem_norm" == "$TCP_MEM_PAGES" && "$cur_lowat" == "$TCP_NOTSENT_LOWAT" && "$cur_syn" == "3" ]]; then
        echo -e "3. TCP 窗口与弱网容错     : ${GREEN}[PASS] TCP上限=${rmem_mb}MB, 初始=${def_kb}KB, notsent=${lowat_kb}KB, SYN重试=${cur_syn}, UDP=${udp_kb}KB${NC}"
        echo -e "   • 内核 tcp_mem 全局硬顶  : ${tcp_mem_norm} 页"
    else
        echo -e "3. TCP 窗口与弱网容错     : ${RED}[FAIL] 参数不匹配（可能被其他 /etc/sysctl.d/*.conf 覆盖）${NC}"
        echo -e "   • 实际值: rmem=${rmem_mb}MB, 初始=${def_kb}KB, notsent=${lowat_kb}KB, SYN重试=${cur_syn}, tcp_mem=[${tcp_mem_norm}]"
        echo -e "   • 预期值: rmem=$((TCP_MAX_BUF/1048576))MB, 初始=$((TCP_DEF_BUF/1024))KB, notsent=$((TCP_NOTSENT_LOWAT/1024))KB, SYN重试=3, tcp_mem=[${TCP_MEM_PAGES}]"
    fi

    # 4. 自适应 initcwnd + 真实 DNS 生效校验 + 出站连通性
    local net_ok=0
    curl -s -I -m 3 https://www.gstatic.com/generate_204 2>/dev/null | grep -q "204" && net_ok=1

    local dns_ok=0 dns_desc=""
    if systemctl is-active --quiet systemd-resolved 2>/dev/null && command -v resolvectl >/dev/null 2>&1; then
        local r_out="" cur_dns="" all_dns=""
        if [[ -n "$def_dev" ]]; then
            r_out=$(SYSTEMD_COLORS=0 resolvectl status "$def_dev" --no-pager 2>/dev/null || true)
        fi
        if [[ -z "$r_out" ]]; then
            r_out=$(SYSTEMD_COLORS=0 resolvectl status --no-pager 2>/dev/null || true)
        fi
        cur_dns=$(awk -F': ' '/Current DNS Server/ {print $2; exit}' <<<"$r_out" | tr -d '[:space:]')
        all_dns=$(awk -F': ' '/DNS Servers/ {print $2; exit}' <<<"$r_out")

        if [[ -z "$cur_dns" ]]; then
            cur_dns=$(SYSTEMD_COLORS=0 resolvectl status --no-pager 2>/dev/null | awk -F': ' '/Current DNS Server/ {print $2; exit}' | tr -d '[:space:]')
        fi
        local first_dns
        first_dns=$(awk '{print $1}' <<<"$all_dns")
        if [[ -z "$cur_dns" && "$first_dns" == "8.8.8.8" ]]; then
            cur_dns="8.8.8.8"
        fi

        local anti_dhcp=0
        if [[ -d /etc/systemd/network ]] && ls /etc/systemd/network/*.d/99-vps-init-dns.conf >/dev/null 2>&1; then
            anti_dhcp=1
        elif command -v nmcli >/dev/null 2>&1 && [[ -n "$def_dev" ]]; then
            local nm_uuid
            nm_uuid=$(nmcli -t -f DEVICE,UUID connection show --active 2>/dev/null | awk -F: -v dev="$def_dev" '$1 == dev {print $2; exit}')
            if [[ -n "$nm_uuid" ]] && nmcli connection show "$nm_uuid" 2>/dev/null | grep -q 'ipv4.ignore-auto-dns:[[:space:]]*yes'; then
                anti_dhcp=1
            fi
        fi

        local lock_tag=""
        [[ "$anti_dhcp" -eq 1 ]] && lock_tag="+防DHCP"

        if [[ "$cur_dns" == "8.8.8.8" ]] && grep -q "1.1.1.1" <<<"$all_dns"; then
            dns_ok=1
            dns_desc="resolved (主用8.8.8.8/备用1.1.1.1${lock_tag})"
        elif [[ "$cur_dns" == "8.8.8.8" ]]; then
            dns_ok=1
            dns_desc="resolved (主用8.8.8.8${lock_tag})"
        else
            dns_ok=0
            dns_desc="resolved (实际首选=${cur_dns:-未知}, 需8.8.8.8)"
        fi
    else
        local ns1="" ns2="" is_locked=0
        ns1=$(awk '/^[[:space:]]*nameserver/ {print $2; exit}' /etc/resolv.conf 2>/dev/null || echo "")
        ns2=$(awk '/^[[:space:]]*nameserver/ {nr++; if (nr==2) {print $2; exit}}' /etc/resolv.conf 2>/dev/null || echo "")
        if command -v lsattr >/dev/null 2>&1 && lsattr /etc/resolv.conf 2>/dev/null | awk '{print $1}' | grep -q 'i'; then
            is_locked=1
        fi

        if [[ "$ns1" == "8.8.8.8" && "$ns2" == "1.1.1.1" ]]; then
            dns_ok=1
            if [[ "$is_locked" -eq 1 ]]; then
                dns_desc="resolv.conf (8.8.8.8+1.1.1.1 已加锁防覆写)"
            else
                dns_desc="resolv.conf (8.8.8.8+1.1.1.1)"
            fi
        else
            dns_ok=0
            dns_desc="resolv.conf (实际首选=${ns1:-无}/备用=${ns2:-无})"
        fi
    fi

    if [[ "$cur_cwnd" == "${INIT_CWND:-20}" && "$dns_ok" -eq 1 && "$net_ok" -eq 1 ]]; then
        echo -e "4. 首屏加速 + 智能DNS连通 : ${GREEN}[PASS] initcwnd=${cur_cwnd}, DNS=${dns_desc}, 204秒返${NC}"
    else
        echo -e "4. 首屏加速 + 智能DNS连通 : ${YELLOW}[WARN] initcwnd=${cur_cwnd:-默认}(预期${INIT_CWND:-20}), DNS=${dns_desc}(ok=${dns_ok}), 204连通=${net_ok}${NC}"
    fi

    # 5. TCP MSS 1380 (IPv4) / 1340 (双栈 IPv6) 钳制
    local mss4_ok=0 mss6_ok=1
    iptables -t mangle -L POSTROUTING -n 2>/dev/null | grep -q "TCPMSS set 1380" && mss4_ok=1
    if [[ "${IPV6_ENABLED:-0}" == "1" ]]; then
        mss6_ok=0
        ip6tables -t mangle -L POSTROUTING -n 2>/dev/null | grep -q "TCPMSS set 1340" && mss6_ok=1
    fi
    if [[ "$mss4_ok" -eq 1 && "$mss6_ok" -eq 1 ]]; then
        if [[ "${IPV6_ENABLED:-0}" == "1" ]]; then
            echo -e "5. TCP MSS 隧道防分片     : ${GREEN}[PASS] IPv4=1380, IPv6=1340 已生效并持久化${NC}"
        else
            echo -e "5. TCP MSS 隧道防分片     : ${GREEN}[PASS] IPv4=1380 已生效（残废 IPv6 已禁用）${NC}"
        fi
    else
        echo -e "5. TCP MSS 隧道防分片     : ${RED}[FAIL] IPv4=${mss4_ok}, IPv6双栈=${mss6_ok}${NC}"
    fi

    # 6. Swap 与 x-ui 真实守护状态核验
    local swap_total xui_oom xui_nofile xui_env xui_gomem="未设置"
    swap_total=$(free -h 2>/dev/null | awk '/^Swap:/ {print $2}')
    if systemctl list-unit-files x-ui.service >/dev/null 2>&1 || [[ -f /etc/systemd/system/x-ui.service ]]; then
        xui_oom=$(systemctl show x-ui.service -p OOMScoreAdjust --value 2>/dev/null || echo "N/A")
        xui_nofile=$(systemctl show x-ui.service -p LimitNOFILE --value 2>/dev/null || echo "N/A")
        xui_env=$(systemctl show x-ui.service -p Environment --value 2>/dev/null || echo "")
        [[ "$xui_env" == *"GOMEMLIMIT="* ]] && xui_gomem=$(grep -o 'GOMEMLIMIT=[^ ]*' <<<"$xui_env" | head -n1 | cut -d= -f2)

        if [[ "$xui_oom" == "$XUI_OOM_SCORE" && "$xui_gomem" == "$XUI_GOMEMLIMIT" ]]; then
            echo -e "6. Swap & x-ui 防爆保护   : ${GREEN}[PASS] Swap=${swap_total:-0B}, OOM=${xui_oom}, GOMEM=${xui_gomem}, 句柄=${xui_nofile}${NC}"
        else
            echo -e "6. Swap & x-ui 防爆保护   : ${RED}[FAIL] Swap=${swap_total:-0B}, 实际 OOM=${xui_oom}/GOMEM=${xui_gomem} (预期 ${XUI_OOM_SCORE}/${XUI_GOMEMLIMIT})${NC}"
        fi
    else
        echo -e "6. Swap & x-ui 防爆保护   : ${GREEN}[PASS] Swap=${swap_total:-0B} (未安装 x-ui，防爆配置已预置)${NC}"
    fi

    # 7. Chrony NTP 时间同步
    if systemctl is-active --quiet chrony 2>/dev/null || systemctl is-active --quiet chronyd 2>/dev/null; then
        echo -e "7. Chrony 毫秒级时间同步  : ${GREEN}[PASS] 运行中 (保障 REALITY/TLS 握手)${NC}"
    else
        echo -e "7. Chrony 毫秒级时间同步  : ${YELLOW}[WARN] Chrony 未运行${NC}"
    fi

    echo -e "${BOLD}=======================================================================${NC}"
    echo ""
}

