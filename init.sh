show_menu() {
    while true; do
        clear
        echo -e "${CYAN}${BOLD}"
        echo "=============================================================="
        echo "  vps-init-suite | 纯净无防火墙网络优化套件 (v${SCRIPT_VERSION} 自适应版)"
        echo "=============================================================="
        echo -e "${NC}"
        echo -e "  ${GREEN}1.${NC} 一键全套深度调优 ${BOLD}(带宽/RTT/并发/fq封顶自适应 + 严格自检)${NC} ${YELLOW}[推荐]${NC}"
        echo -e "  ${GREEN}2.${NC} 运行系统调优状态一键自检"
        echo -e "  ${GREEN}3.${NC} 一键安装 / 更新 3x-ui 面板"
        echo -e "  ${RED}0.${NC} 退出脚本"
        echo ""
        echo "--------------------------------------------------------------"

        local choice=""
        prompt_read "请输入操作编号 [0-3]: " choice
        echo ""

        case "$choice" in
            1)
                optimize_proxy_stability_and_speed
                verify_optimization
                prompt_read "按回车键返回主菜单..." _
                ;;
            2)
                verify_optimization
                prompt_read "按回车键返回主菜单..." _
                ;;
            3)
                install_3xui
                prompt_read "按回车键返回主菜单..." _
                ;;
            0)
                log_info "已退出 vps-init-suite。"
                exit 0
                ;;
            *)
                log_warn "无效输入，请输入 0 到 3 之间的数字！"
                sleep 1
                ;;
        esac
    done
}

